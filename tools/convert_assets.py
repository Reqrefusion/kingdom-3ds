#!/usr/bin/env python3
"""Build-time data generation for the translated port.

Inputs are the pinned original files only:
  - PNG images            -> <out>/assets/.../<name>.png.argb   (u32 w, u32 h, ARGB pixels)
  - nokiafc22.ttf, 04b03  -> <out>/fonts/<font>_<size>.font
  - assets/levels/compiled/fields.oel -> game/level_fields.inc   (the XML as C data)
  - WeatherPresets.as     -> game/WeatherPresets.c                (the preset objects as C data)

Usage: python tools/convert_assets.py --source <kingdom source root> --out translit_assets
"""
import argparse
import re
import struct
import xml.etree.ElementTree as ET
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parents[1]


def write_lf(path: Path, text: str):
    """generated sources always use LF (Windows would write CRLF and make the files differ from the repo)"""
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def convert_png(src: Path, dst: Path):
    img = Image.open(src).convert("RGBA")
    w, h = img.size
    data = bytearray(struct.pack("<II", w, h))
    for r, g, b, a in img.getdata():
        data += struct.pack("<I", (a << 24) | (r << 16) | (g << 8) | b)
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_bytes(bytes(data))


def convert_font(ttf: Path, name: str, size: int, out_dir: Path):
    font = ImageFont.truetype(str(ttf), size)
    ascent, descent = font.getmetrics()
    out = bytearray(struct.pack("<iii", ascent, descent, ascent + descent))
    for code in range(32, 127):
        ch = chr(code)
        advance = int(round(font.getlength(ch)))
        canvas_w, canvas_h = max(1, advance + size), ascent + descent + size
        img = Image.new("L", (canvas_w, canvas_h), 0)
        draw = ImageDraw.Draw(img)
        draw.fontmode = "1"  # pixel fonts: no smoothing
        draw.text((0, 0), ch, font=font, fill=255)
        bbox = img.getbbox()
        if bbox is None:
            out += struct.pack("<BBBbb", advance, 0, 0, 0, 0)
            continue
        x0, y0, x1, y1 = bbox
        glyph = img.crop(bbox)
        out += struct.pack("<BBBbb", advance, x1 - x0, y1 - y0, x0, y0 - ascent)
        out += bytes(glyph.getdata())
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{name}_{size}.font").write_bytes(bytes(out))


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def convert_level(oel: Path, dst: Path):
    root = ET.parse(oel).getroot()
    lines = [
        "/* Generated by tools/convert_assets.py from assets/levels/compiled/fields.oel.",
        "   The XML is kept as data so PlayState.buildLevel can walk it like the",
        "   original does with E4X. */",
        "#include \"level.h\"",
        "",
    ]
    sections = []
    for section in root:
        if section.tag in ("width", "height", "ground"):
            continue
        nodes = [f'\t{{{c_string(n.tag)}, {n.get("x")}, {n.get("y")}}},' for n in section]
        ident = f"level_{section.tag}"
        lines.append(f"static const OelNode {ident}_nodes[] = {{")
        lines += nodes or ["\t{0},"]
        lines.append("};")
        sections.append((section.tag, ident, len(nodes)))
    ground = root.find("ground")
    lines.append("")
    lines.append("static const OelSection level_sections[] = {")
    for tag, ident, n in sections:
        lines.append(f"\t{{{c_string(tag)}, {ident}_nodes, {n}}},")
    lines.append("};")
    lines.append("")
    lines.append("const OelLevel Level_fields = {")
    lines.append(f"\t.backdropFarImg = {c_string(root.get('backdropFarImg'))},")
    lines.append(f"\t.backdropCloseImg = {c_string(root.get('backdropCloseImg'))},")
    lines.append(f"\t.waterHeight = {root.get('waterHeight')},")
    lines.append(f"\t.groundTileWidth = {ground.get('tileWidth')},")
    lines.append(f"\t.groundTileHeight = {ground.get('tileHeight')},")
    lines.append(f"\t.ground = {c_string(ground.text or '')},")
    lines.append("\t.sections = level_sections,")
    lines.append(f"\t.sectionCount = {len(sections)},")
    lines.append("};")
    write_lf(dst, "\n".join(lines) + "\n")


WEATHER_FIELDS = ["sky", "horizon", "haze", "darknessColor", "darkness", "contrast", "saturation",
                  "ambient", "wind", "fog", "rain", "timeOfDay", "sunTint", "ambientAmount"]


def convert_presets(src: Path, dst: Path):
    text = src.read_text()
    presets = re.findall(r"public static const (\w+):Object\s*=\s*\{(.*?)\}", text, re.S)
    out = [
        "/* Generated by tools/convert_assets.py from WeatherPresets.as.",
        "   Each AS3 preset object becomes a WeatherState with a mask of the",
        "   properties it defines (for..in only visits those). */",
        "#include \"game.h\"",
        "",
    ]
    names = []
    for name, body in presets:
        fields = dict(re.findall(r"'(\w+)'\s*:\s*([-0-9.xXa-fA-F]+)", body))
        mask = " | ".join(f"WEATHER_HAS_{k}" for k in fields) or "0"
        inits = [f".{k} = {v}" for k, v in fields.items()]
        out.append(f"static WeatherState WeatherPresets_{name}_obj = {{.name = \"{name}\", .has = {mask}, {', '.join(inits)}}};")
        names.append(name)
    out.append("")
    for name in names:
        out.append(f"WeatherState *const WeatherPresets_{name} = &WeatherPresets_{name}_obj;")
    write_lf(dst, "\n".join(out) + "\n")
    header = dst.with_name("WeatherPresets.h")
    write_lf(header, "#ifndef TRANSLIT_WEATHERPRESETS_H\n#define TRANSLIT_WEATHERPRESETS_H\n" +
                      "".join(f"extern WeatherState *const WeatherPresets_{n};\n" for n in names) + "#endif\n")


def convert_audio(src, out):
    """MP3 -> raw signed 16-bit little-endian mono 22050 Hz (<name>.mp3.pcm),
    the format platform/3ds/media.c streams into NDSP. Needs ffmpeg on PATH."""
    import shutil, subprocess
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg is None:
        print("ffmpeg not found: audio skipped (the game runs silent)")
        return
    for mp3 in sorted((src / "assets").rglob("*.mp3")):
        rel = mp3.relative_to(src)
        dst = out / (str(rel) + ".pcm")
        dst.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run([ffmpeg, "-loglevel", "error", "-y", "-i", str(mp3), "-f", "s16le",
                        "-acodec", "pcm_s16le", "-ac", "1", "-ar", "22050", str(dst)], check=True)
        print("audio", rel)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True, type=Path)
    ap.add_argument("--out", default=HERE / "translit_assets", type=Path)
    ap.add_argument("--audio", action="store_true", help="also convert MP3s for the 3DS build (ffmpeg)")
    args = ap.parse_args()
    src = args.source
    for png in sorted((src / "assets" / "gfx").glob("*.png")):
        convert_png(png, args.out / "assets" / "gfx" / (png.name + ".argb"))
    convert_png(src / "org/flixel/data/default.png", args.out / "org/flixel/data/default.png.argb")
    fonts = {"system": src / "org/flixel/data/nokiafc22.ttf", "04b03": src / "assets/04b03.ttf"}
    for name, ttf in fonts.items():
        for size in (8, 16, 32):
            convert_font(ttf, name, size, args.out / "fonts")
    convert_level(src / "assets/levels/compiled/fields.oel", HERE / "game" / "level_fields.c")
    convert_presets(src / "WeatherPresets.as", HERE / "game" / "WeatherPresets.c")
    if args.audio:
        convert_audio(src, args.out)
    print("assets written to", args.out)


if __name__ == "__main__":
    main()
