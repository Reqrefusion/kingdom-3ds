#!/usr/bin/env python3
"""Writes tests/sound_expected.h from the ORIGINAL ActionScript source.

The phase table (PlayState.PHASES / PHASES_CYCLE: weather preset, duration,
tween time, callback, music) is parsed from PlayState.as, so the C test
verify_sound compares the translation against the source, not against a copy
typed by hand.

  python tests/gen_sound_expected.py [path/to/PlayState.as]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_AS = (ROOT / "../work/kingdom-source/56d4e622461b72df8fa8f69d09fbd63dab7a1346/"
              "kingdom-56d4e622461b72df8fa8f69d09fbd63dab7a1346/PlayState.as")

src_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_AS
src = src_path.read_text(encoding="utf-8", errors="replace")

# [Embed(source="/assets/music/night2.mp3")] private var MusicNight2:Class;
embeds = dict(re.findall(r'\[Embed\(source="([^"]+)"\)\]\s*private var (\w+):Class', src))
embeds = {name: path for path, name in embeds.items()}

ROW = re.compile(r"\[\s*(WeatherPresets\.\w+|null)\s*,\s*(\d+)\s*,\s*(null|\d+)\s*,\s*(\w+|null)\s*,\s*(\w+|null)\s*\]")


def table(name):
    m = re.search(r"public const %s:Array = \[(.*?)\n\s*\];" % name, src, re.S)
    assert m, name
    body = re.sub(r"//[^\n]*", "", m.group(1))  # comments may contain brackets
    rows = ROW.findall(body)
    assert rows, name
    return rows


def c_row(r):
    weather, duration, tween, callback, music = r
    w = "NULL" if weather == "null" else "WeatherPresets_" + weather.split(".")[1]
    t_has = "false" if tween == "null" else "true"
    t_val = "0" if tween == "null" else tween
    m = "NULL" if music == "null" else '"%s"' % embeds[music]
    cb = "false" if callback == "null" else "true"
    return "\t{%s, %s, %s, %s, %s, %s}, /* %s */" % (w, duration, t_has, t_val, cb, m, callback)


out = ["/* GENERATED by tests/gen_sound_expected.py from PlayState.as - do not edit. */",
       "typedef struct SoundExpectedRow {",
       "\tWeatherState *weather; Number duration; bool hasTween; Number tween; bool hasCallback; const char *music;",
       "} SoundExpectedRow;"]
# WeatherPresets_* are extern variables, not constant expressions, so the rows
# are emitted as macros that the test expands into an automatic array.
for const, name in (("PHASES", "SOUND_EXPECTED_PHASES"), ("PHASES_CYCLE", "SOUND_EXPECTED_CYCLE")):
    rows = table(const)
    out.append("#define %s \\" % name)
    out += [c_row(r).replace(" /*", " /*").split(" /*")[0].rstrip() + " \\" for r in rows]
    out.append("")
(ROOT / "tests/sound_expected.h").write_text("\n".join(out) + "\n", encoding="utf-8")
print("phases", len(table("PHASES")), "cycle", len(table("PHASES_CYCLE")))
